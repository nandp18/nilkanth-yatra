// Builds js/data/printdata.js (coastline, rivers, lakes for the print map) from
// Natural Earth (public domain), clipped to the map extent and simplified.
// Run: node tools/build-print.mjs
import { writeFileSync } from 'node:fs';

const BASE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/';
const get = async (f) => (await fetch(BASE + f + '.geojson')).json();
const BBOX = [65.5, 4.5, 98.5, 36.5];           // map extent plus a margin
const TOL = 0.012;                               // simplification tolerance, degrees
const RIVERS = new Set(['Ganges', 'Yamuna', 'Brahmaputra', 'Dihang', 'Yarlung', 'Indus', 'Sutlej', 'Chenab',
  'Narmada', 'Godävari', 'Krishna', 'Mahäna Nadï', 'Irrawaddy Delta', 'Ayeyarwady']);

// Sutherland–Hodgman against an axis-aligned box (fine for land rings)
function clipRing(ring, [x0, y0, x1, y1]) {
  const edges = [
    [(p) => p[0] >= x0, (a, b) => [x0, a[1] + ((b[1] - a[1]) * (x0 - a[0])) / (b[0] - a[0])]],
    [(p) => p[0] <= x1, (a, b) => [x1, a[1] + ((b[1] - a[1]) * (x1 - a[0])) / (b[0] - a[0])]],
    [(p) => p[1] >= y0, (a, b) => [a[0] + ((b[0] - a[0]) * (y0 - a[1])) / (b[1] - a[1]), y0]],
    [(p) => p[1] <= y1, (a, b) => [a[0] + ((b[0] - a[0]) * (y1 - a[1])) / (b[1] - a[1]), y1]],
  ];
  let out = ring;
  for (const [inside, cut] of edges) {
    const input = out; out = [];
    for (let i = 0; i < input.length; i++) {
      const a = input[(i + input.length - 1) % input.length], b = input[i];
      if (inside(b)) { if (!inside(a)) out.push(cut(a, b)); out.push(b); }
      else if (inside(a)) out.push(cut(a, b));
    }
    if (!out.length) break;
  }
  return out;
}

function simplify(pts, tol) {          // Douglas–Peucker
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let dmax = 0, idx = -1;
    const [ax, ay] = pts[a], [bx, by] = pts[b], dx = bx - ax, dy = by - ay, L = Math.hypot(dx, dy) || 1e-12;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / L;
      if (d > dmax) { dmax = d; idx = i; }
    }
    if (dmax > tol) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const flat = (pts) => pts.flatMap(([x, y]) => [+x.toFixed(3), +y.toFixed(3)]);
const inBox = ([x, y]) => x >= BBOX[0] && x <= BBOX[2] && y >= BBOX[1] && y <= BBOX[3];
const polys = (g) => (g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : []);
const lines = (g) => (g.type === 'LineString' ? [g.coordinates] : g.type === 'MultiLineString' ? g.coordinates : []);

const [land, rivers, lakes] = await Promise.all([get('ne_10m_land'), get('ne_50m_rivers_lake_centerlines'), get('ne_50m_lakes')]);

const LAND = [];
for (const f of land.features) for (const poly of polys(f.geometry)) {
  const ring = clipRing(poly[0], BBOX);
  const s = simplify(ring, TOL);
  if (s.length >= 4) LAND.push(flat(s));
}

const RIV = [];
for (const f of rivers.features) {
  if (!RIVERS.has(f.properties.name)) continue;
  for (const ln of lines(f.geometry)) {
    const pts = ln.filter(inBox);
    if (pts.length > 1) RIV.push(flat(simplify(pts, TOL / 2)));
  }
}

const LAKES = [];
for (const f of lakes.features) for (const poly of polys(f.geometry)) {
  if (!poly[0].some(inBox)) continue;
  const s = simplify(poly[0], TOL / 2);
  if (s.length >= 4) LAKES.push(flat(s));
}

const out = `// Generated by tools/build-print.mjs from Natural Earth (public domain). Do not edit.
export const LAND = ${JSON.stringify(LAND)};
export const RIVERS = ${JSON.stringify(RIV)};
export const LAKES = ${JSON.stringify(LAKES)};
`;
writeFileSync(new URL('../js/data/printdata.js', import.meta.url), out);
console.log(`land rings ${LAND.length}, rivers ${RIV.length}, lakes ${LAKES.length}, ${(out.length / 1024).toFixed(0)} KB`);
