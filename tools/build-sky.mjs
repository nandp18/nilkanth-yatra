// Builds js/data/skydata.js from the d3-celestial catalogs (BSD-3, © Olaf Frohn).
// Run: node tools/build-sky.mjs
import { writeFileSync } from 'node:fs';

const BASE = 'https://raw.githubusercontent.com/ofrohn/d3-celestial/master/data/';
const get = async (f) => (await fetch(BASE + f)).json();
const ra = (lon) => +(((lon % 360) + 360) % 360).toFixed(2);
const r2 = (x) => +x.toFixed(2);

const [stars, lines, mw] = await Promise.all([get('stars.6.json'), get('constellations.lines.json'), get('mw.json')]);

// Stars to magnitude 5.5 (naked eye under a dark sky): flat [ra, dec, mag, bv, ...]
const S = [];
const hipIndex = {};
for (const f of stars.features) {
  const { mag, bv } = f.properties;
  if (mag > 5.5) continue;
  const [lon, lat] = f.geometry.coordinates;
  hipIndex[f.id] = S.length / 4;
  S.push(ra(lon), r2(lat), +mag.toFixed(1), +(parseFloat(bv) || 0.6).toFixed(2));
}

// Constellation stick figures: array of polylines, each a flat [ra, dec, ...]
const L = [];
for (const f of lines.features) {
  for (const seg of f.geometry.coordinates) L.push(seg.flatMap(([lon, lat]) => [ra(lon), r2(lat)]));
}

// Milky Way brightness contours ol1 (faint) .. ol5 (bright); thin the outer rings
const M = mw.features.map((f) => {
  const step = f.id === 'ol1' || f.id === 'ol2' ? 3 : f.id === 'ol3' ? 2 : 1;
  return f.geometry.coordinates.flatMap((poly) => poly.map((ring) =>
    ring.filter((_, i) => i % step === 0).flatMap(([lon, lat]) => [+ra(lon).toFixed(1), +lat.toFixed(1)])));
});

// Names: Sanskrit (nakshatra yogatara / traditional) with the Western name
const NAMED = {
  65474: ['Chitra', 'Spica'], 69673: ['Swati', 'Arcturus'], 21421: ['Rohini', 'Aldebaran'],
  49669: ['Magha', 'Regulus'], 80763: ['Jyeshtha', 'Antares'], 11767: ['Dhruva', 'Polaris'],
  32349: ['Lubdhaka', 'Sirius'], 27989: ['Ardra', 'Betelgeuse'], 37826: ['Punarvasu', 'Pollux'],
  97649: ['Shravana', 'Altair'], 30438: ['Agastya', 'Canopus'], 17702: ['Krittika', 'Pleiades'],
  91262: ['Abhijit', 'Vega'], 24608: ['Brahmahridaya', 'Capella'], 24436: ['', 'Rigel'],
  37279: ['', 'Procyon'], 102098: ['', 'Deneb'], 113368: ['', 'Fomalhaut'],
};
const N = Object.entries(NAMED)
  .filter(([hip]) => hip in hipIndex)
  .map(([hip, [skt, west]]) => [hipIndex[hip], skt, west]);

const out = `// Generated by tools/build-sky.mjs from d3-celestial (BSD-3, © Olaf Frohn). Do not edit.
// STARS: flat [raDeg, decDeg, mag, bv]; LINES: polylines of [ra, dec]; MW: Milky Way levels 1..5.
export const STARS = ${JSON.stringify(S)};
export const LINES = ${JSON.stringify(L)};
export const MW = ${JSON.stringify(M)};
export const NAMES = ${JSON.stringify(N)};
`;
writeFileSync(new URL('../js/data/skydata.js', import.meta.url), out);
console.log(`stars ${S.length / 4}, lines ${L.length}, mw rings ${M.map((l) => l.length).join('/')}, names ${N.length}, ${(out.length / 1024).toFixed(0)} KB`);
